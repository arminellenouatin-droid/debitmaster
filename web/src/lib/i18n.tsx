const dicts: Record<string, Dict> = { fr, en }

interface I18nCtx {
  lang: string
  setLang: (l: string) => void
  t: (k: string) => string
}

const Ctx = createContext<I18nCtx>({ lang: 'fr', setLang: () => {}, t: (k) => k })

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<string>(() => localStorage.getItem('dm.lang') || 'fr')
  useEffect(() => {
    localStorage.setItem('dm.lang', lang)
    document.documentElement.lang = lang
  }, [lang])
  const t = (k: string) => dicts[lang]?.[k] ?? dicts.fr[k] ?? k
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)
